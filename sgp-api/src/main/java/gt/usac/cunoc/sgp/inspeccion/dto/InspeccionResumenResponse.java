package gt.usac.cunoc.sgp.inspeccion.dto;

import com.fasterxml.jackson.databind.JsonNode;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

public record InspeccionResumenResponse(
    UUID id,
    UUID puenteId,
    String puenteNombre,
    UUID versionFormularioId,
    String versionFormularioCodigo,
    UUID autorId,
    String rolAutorCreacion,
    String nombreAutorCapturado,
    String tipo,
    String estado,
    LocalDate fechaInspeccion,
    String dispositivoId,
    JsonNode datos,
    Instant creadoEn,
    Instant actualizadoEn,
    String codigoPuente,
    String departamentoNombre,
    String municipioNombre,
    String codigoVersionFormulario,
    Double porcentajeAvance,
    Instant ultimaActividadEn,
    String nombrePuente,
    String rolAutor,
    String nombreAutor,
    Double latitudInicio,
    Double longitudInicio,
    BigDecimal precisionGpsM,
    BigDecimal distanciaAlPuenteM,
    boolean advertenciaGps,
    String mensajeAdvertenciaGps,
    boolean datosPermanentesConfirmados,
    DatosPermanentesResponse datosPermanentes,
    List<AcompananteResponse> acompanantes,
    /** Inspección publicada que esta corrección reemplaza (RN-INS-08). */
    UUID supersedeAId,
    String motivoCorreccion,
    /** Corrección publicada que supera a esta inspección; nulo si sigue vigente. */
    UUID superadaPorId) {

  public InspeccionResumenResponse(
      UUID id,
      UUID puenteId,
      String codigoPuente,
      String nombrePuente,
      String departamentoNombre,
      String municipioNombre,
      UUID versionFormularioId,
      String codigoVersionFormulario,
      UUID autorId,
      String rolAutorCreacion,
      String nombreAutorCapturado,
      String estado,
      String tipo,
      LocalDate fechaInspeccion,
      Double porcentajeAvance,
      Instant ultimaActividadEn,
      Instant creadoEn,
      Instant actualizadoEn) {
    this(
        id,
        puenteId,
        nombrePuente,
        versionFormularioId,
        codigoVersionFormulario,
        autorId,
        rolAutorCreacion,
        nombreAutorCapturado,
        tipo,
        estado,
        fechaInspeccion,
        null,
        null,
        creadoEn,
        actualizadoEn,
        codigoPuente,
        departamentoNombre,
        municipioNombre,
        codigoVersionFormulario,
        porcentajeAvance,
        ultimaActividadEn,
        nombrePuente,
        rolAutorCreacion,
        nombreAutorCapturado,
        null,
        null,
        null,
        null,
        false,
        null,
        false,
        null,
        List.of(),
        null,
        null,
        null);
  }

  /** La misma respuesta marcada como superada por la corrección publicada indicada. */
  public InspeccionResumenResponse conSuperadaPor(UUID correccionPublicadaId) {
    return new InspeccionResumenResponse(
        id,
        puenteId,
        puenteNombre,
        versionFormularioId,
        versionFormularioCodigo,
        autorId,
        rolAutorCreacion,
        nombreAutorCapturado,
        tipo,
        estado,
        fechaInspeccion,
        dispositivoId,
        datos,
        creadoEn,
        actualizadoEn,
        codigoPuente,
        departamentoNombre,
        municipioNombre,
        codigoVersionFormulario,
        porcentajeAvance,
        ultimaActividadEn,
        nombrePuente,
        rolAutor,
        nombreAutor,
        latitudInicio,
        longitudInicio,
        precisionGpsM,
        distanciaAlPuenteM,
        advertenciaGps,
        mensajeAdvertenciaGps,
        datosPermanentesConfirmados,
        datosPermanentes,
        acompanantes,
        supersedeAId,
        motivoCorreccion,
        correccionPublicadaId);
  }
}
